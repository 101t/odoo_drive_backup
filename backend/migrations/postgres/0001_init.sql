-- Initial schema for odoo-backup on PostgreSQL (mirrors migrations/sqlite/0001_init.sql).

CREATE TABLE users (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT        NOT NULL,
    password_hash TEXT        NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL
);
-- Usernames are case-insensitive (like COLLATE NOCASE on SQLite).
CREATE UNIQUE INDEX users_username_key ON users (LOWER(username));

CREATE TABLE sessions (
    token_hash TEXT        PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_sessions_user    ON sessions(user_id);
CREATE INDEX idx_sessions_expires ON sessions(expires_at);

CREATE TABLE instances (
    id                  BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT        NOT NULL UNIQUE,
    url                 TEXT        NOT NULL,
    master_password_enc TEXT,
    verify_tls          BOOLEAN     NOT NULL DEFAULT TRUE,
    timeout_secs        BIGINT      NOT NULL DEFAULT 3600,
    notes               TEXT        NOT NULL DEFAULT '',
    odoo_version        TEXT,
    databases_json      TEXT        NOT NULL DEFAULT '[]',
    last_checked_at     TIMESTAMPTZ,
    last_check_error    TEXT,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL
);

CREATE TABLE destinations (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT        NOT NULL UNIQUE,
    kind        TEXT        NOT NULL,
    config_json TEXT        NOT NULL DEFAULT '{}',
    secret_enc  TEXT,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE jobs (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT        NOT NULL,
    instance_id    BIGINT      NOT NULL REFERENCES instances(id) ON DELETE CASCADE,
    all_databases  BOOLEAN     NOT NULL DEFAULT FALSE,
    databases_json TEXT        NOT NULL DEFAULT '[]',
    format         TEXT        NOT NULL DEFAULT 'zip',
    cron           TEXT        NOT NULL,
    timezone       TEXT        NOT NULL DEFAULT 'UTC',
    enabled        BOOLEAN     NOT NULL DEFAULT TRUE,
    keep_last      BIGINT      NOT NULL DEFAULT 7,
    keep_daily     BIGINT      NOT NULL DEFAULT 7,
    keep_weekly    BIGINT      NOT NULL DEFAULT 4,
    keep_monthly   BIGINT      NOT NULL DEFAULT 6,
    keep_yearly    BIGINT      NOT NULL DEFAULT 0,
    retries        BIGINT      NOT NULL DEFAULT 2,
    verify_archive BOOLEAN     NOT NULL DEFAULT TRUE,
    next_run_at    TIMESTAMPTZ,
    last_run_at    TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_jobs_instance ON jobs(instance_id);
CREATE INDEX idx_jobs_next_run ON jobs(next_run_at) WHERE enabled;

CREATE TABLE job_destinations (
    job_id         BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
    destination_id BIGINT NOT NULL REFERENCES destinations(id) ON DELETE CASCADE,
    PRIMARY KEY (job_id, destination_id)
);
CREATE INDEX idx_job_destinations_dest ON job_destinations(destination_id);

CREATE TABLE runs (
    id                 BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind               TEXT        NOT NULL DEFAULT 'backup',
    job_id             BIGINT      REFERENCES jobs(id) ON DELETE SET NULL,
    instance_id        BIGINT      REFERENCES instances(id) ON DELETE SET NULL,
    instance_name      TEXT        NOT NULL,
    database           TEXT        NOT NULL,
    format             TEXT        NOT NULL,
    trigger            TEXT        NOT NULL,
    status             TEXT        NOT NULL,
    phase              TEXT,
    error              TEXT,
    file_name          TEXT,
    size_bytes         BIGINT,
    sha256             TEXT,
    md5                TEXT,
    odoo_version       TEXT,
    source_artifact_id BIGINT,
    restore_options    TEXT,
    attempt            BIGINT      NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL,
    started_at         TIMESTAMPTZ,
    finished_at        TIMESTAMPTZ
);
CREATE INDEX idx_runs_created     ON runs(created_at DESC);
CREATE INDEX idx_runs_status      ON runs(status);
CREATE INDEX idx_runs_job_db      ON runs(job_id, database);
CREATE INDEX idx_runs_instance_db ON runs(instance_id, database, status);

CREATE TABLE artifacts (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id           BIGINT      NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
    destination_id   BIGINT      REFERENCES destinations(id) ON DELETE SET NULL,
    destination_name TEXT        NOT NULL,
    destination_kind TEXT        NOT NULL,
    status           TEXT        NOT NULL,
    remote_id        TEXT,
    remote_path      TEXT,
    web_url          TEXT,
    size_bytes       BIGINT,
    error            TEXT,
    created_at       TIMESTAMPTZ NOT NULL,
    stored_at        TIMESTAMPTZ,
    deleted_at       TIMESTAMPTZ,
    delete_reason    TEXT
);
CREATE INDEX idx_artifacts_run  ON artifacts(run_id);
CREATE INDEX idx_artifacts_dest ON artifacts(destination_id, status);

CREATE TABLE run_logs (
    id      BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id  BIGINT      NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
    ts      TIMESTAMPTZ NOT NULL,
    level   TEXT        NOT NULL,
    message TEXT        NOT NULL
);
CREATE INDEX idx_run_logs_run ON run_logs(run_id, id);
CREATE INDEX idx_run_logs_ts  ON run_logs(ts);

CREATE TABLE notification_channels (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT        NOT NULL,
    kind        TEXT        NOT NULL,
    config_json TEXT        NOT NULL DEFAULT '{}',
    secret_enc  TEXT,
    on_success  BOOLEAN     NOT NULL DEFAULT FALSE,
    on_failure  BOOLEAN     NOT NULL DEFAULT TRUE,
    enabled     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
